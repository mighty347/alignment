"""
Module: modules/generate_chainage.py
Purpose: Module 2 — Generate continuous chainage points along the alignment.

Engineering Basis:
    Indian Railways ESPs require cross-sections and profile data at
    fixed intervals, standard is 20 meters. This module interpolates
    points exactly every 20m along the UTM LineString generated by Module 1.

Input: AlignmentResult (Module 1)
Output: ChainageResult (DataFrame of interpolated points)

Standards: RDSO / Indian Railways BG
Author   : Railway ESP Generator
"""
from __future__ import annotations

import pandas as pd
import numpy as np
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from shapely.geometry import LineString
from pyproj import Transformer

from modules.read_kml import AlignmentResult
from utils.geo_utils import build_transformer, format_chainage
from utils.logger import get_logger


logger = get_logger(__name__)


class ChainageError(Exception):
    """Custom exception for Chainage Generator errors."""
    pass


@dataclass
class ChainageResult:
    """Result object returned by ChainageGenerator.

    Attributes:
        dataframe: Pandas DataFrame containing the interpolated points.
            Columns: chainage_m, chainage_str, easting, northing, latitude, longitude
        metadata: Engineering metadata dictionary.
    """
    dataframe: pd.DataFrame
    metadata: dict[str, Any] = field(default_factory=dict)


class ChainageGenerator:
    """Interpolates points at fixed intervals along the railway alignment.

    Implements Module 2 of the ESP Generator pipeline.

    Args:
        config: Configuration dictionary loaded from config.yaml.

    Example:
        >>> chainage_result = ChainageGenerator(config).generate(alignment_result)
    """

    def __init__(self, config: dict[str, Any]) -> None:
        self.config = config
        self._alignment_cfg = config.get("alignment", {})
        self.interval = float(self._alignment_cfg.get("chainage_interval", 20.0))
        self.start_chainage = float(self._alignment_cfg.get("start_chainage", 0.0))
        self.logger = get_logger(self.__class__.__name__)
        self.logger.info("Initialized %s with interval %.2fm.", self.__class__.__name__, self.interval)

    def generate(self, alignment_result: AlignmentResult) -> ChainageResult:
        """Generate chainage points from the raw alignment.

        Args:
            alignment_result: Output from Module 1 (KMLReader).

        Returns:
            ChainageResult containing the interpolated points dataframe.

        Raises:
            ChainageError: If the alignment is invalid or generation fails.
        """
        self.logger.info("Starting chainage generation...")
        try:
            if not np.isfinite(self.interval) or self.interval <= 0.0:
                raise ChainageError(
                    f"chainage_interval must be a finite positive value; got {self.interval!r}."
                )
            if not np.isfinite(self.start_chainage):
                raise ChainageError(
                    f"start_chainage must be finite; got {self.start_chainage!r}."
                )
            line: LineString = alignment_result.alignment_line
            if line.is_empty or line.length <= 0:
                raise ChainageError("Input alignment LineString is empty or has zero length.")

            total_length_m = line.length
            
            # If prescribed design VIPs are set (e.g. 1277.05m), truncate alignment to match design sheet length
            prescribed_vips = self.config.get("vertical", {}).get("prescribed_vips", [])
            if prescribed_vips:
                prescribed_chainages = [float(vip["ch"]) for vip in prescribed_vips]
                if not np.all(np.isfinite(prescribed_chainages)):
                    raise ChainageError("All prescribed VIP chainages must be finite.")
                max_prescribed_distance = max(prescribed_chainages) - self.start_chainage
                if max_prescribed_distance <= 0.0:
                    raise ChainageError(
                        "The final prescribed VIP chainage must be greater than start_chainage."
                    )
                if total_length_m > max_prescribed_distance:
                    self.logger.info(
                        "Clipping alignment length from %.2fm to prescribed design distance %.2fm",
                        total_length_m, max_prescribed_distance,
                    )
                    total_length_m = max_prescribed_distance

            self.logger.debug("Alignment UTM length: %.3f m", total_length_m)

            # Generate distances: 0, 20, 40, ..., total_length
            distances = np.arange(0, total_length_m, self.interval)
            
            # If the last point isn't exactly at the end, append the total length to close the line
            if len(distances) == 0 or not np.isclose(distances[-1], total_length_m):
                distances = np.append(distances, total_length_m)

            self.logger.info("Interpolating %d points at %.2fm intervals.", len(distances), self.interval)

            # Interpolate points along the Shapely LineString
            interpolated_points = [line.interpolate(d) for d in distances]
            eastings = np.array([p.x for p in interpolated_points])
            northings = np.array([p.y for p in interpolated_points])

            # Transform interpolated UTM points back to WGS84 for reference
            # Build transformer from UTM -> WGS84
            transformer = build_transformer(
                source_epsg=alignment_result.utm_info.epsg_str,
                target_epsg="EPSG:4326"
            )
            
            self.logger.debug("Inverse projecting UTM -> WGS84.")
            # transformer.transform returns (X, Y) which is (lon, lat) because always_xy=True
            longitudes, latitudes = transformer.transform(eastings, northings)

            # Calculate actual chainage values incorporating start_chainage
            actual_chainages = distances + self.start_chainage
            chainage_strs = [format_chainage(c) for c in actual_chainages]

            # Build DataFrame
            df = pd.DataFrame({
                "chainage_m": actual_chainages,
                "chainage_str": chainage_strs,
                "easting": eastings,
                "northing": northings,
                "latitude": latitudes,
                "longitude": longitudes,
            })

            metadata = {
                "interval_m": self.interval,
                "start_chainage_m": self.start_chainage,
                "total_chainage_m": actual_chainages[-1],
                "total_points": len(df),
                "crs": alignment_result.utm_info.epsg_str
            }

            self.logger.info("Chainage generation complete: %d points created.", len(df))
            return ChainageResult(dataframe=df, metadata=metadata)

        except Exception as e:
            self.logger.error("Chainage generation failed: %s", str(e))
            raise ChainageError(f"Chainage generation failed: {e}") from e

